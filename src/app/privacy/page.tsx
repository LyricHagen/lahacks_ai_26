import { DocLayout } from "@/components/doc-layout";
import { createLogger } from "@/lib/log";
import { withPage } from "@/lib/request-context";

export const metadata = { title: "Privacy policy" };

const log = createLogger("page.privacy");

export default async function PrivacyPage() {
  return withPage("privacy", async () => {
    log.debug("rendering privacy policy");
    return (
      <DocLayout eyebrow="/privacy" title="Privacy policy" description="Last updated 17 October 2026. Plain language, no surprises.">
        <h2>Summary</h2>
        <p>
          Who2Ask is a prototype built for a hackathon. Every colleague, team, calendar and message history in it is synthetic: generated by a
          script, not copied from any real company. The only real personal data we hold is the account you create and what you type into it.
        </p>

        <h2>What we store</h2>
        <h3>Your account</h3>
        <p>
          Your email address, a bcrypt password hash (never the password itself), your role, whether an admin has approved the account, when you
          signed up and last logged in, and which synthetic colleague you play inside the fake company.
        </p>
        <h3>Cookies</h3>
        <p>
          Two functional cookies, both httpOnly: the session cookie that keeps you signed in (for up to seven days), and, only if you turn it on,
          the demo mode toggle. Neither is used for tracking.
        </p>
        <h3>Sign in attempts</h3>
        <p>
          To limit password guessing, the app counts signup and login attempts per network address. The counter holds the address and a count
          for one window (at most an hour) and is overwritten after that.
        </p>
        <h3>Your onboarding profile</h3>
        <p>The team, role, start date and focus areas you enter during setup. These are used only to rank colleagues for your asks.</p>
        <h3>Your asks</h3>
        <p>
          The text of each problem you describe, the shortlist produced for it, the explanation, the drafted message, and the status you set
          (for example, sent or resolved). Who2Ask does not see whether you actually sent a message, only what you mark.
        </p>
        <h3>Usage and cost records</h3>
        <p>
          For each model call: the purpose, the model name, token counts, latency, estimated cost, and whether a live result or a cached demo
          result was used, tied to your account so admins can see spend per user. The text sent to the model is not stored in these records.
        </p>

        <h2>What we do not store</h2>
        <ul>
          <li>Contents of any real email, chat or calendar. The synthetic company has free and busy blocks only.</li>
          <li>Anything about you from outside the app.</li>
          <li>Tracking cookies or third party analytics.</li>
        </ul>

        <h2>Logs</h2>
        <p>
          The app writes detailed technical logs so problems can be debugged. Secrets and API keys are redacted automatically before a line is
          written. In development, and for admins, recent log lines are attached to API responses and visible in the debug drawer. Server logs
          are kept in memory (the last 500 lines) and in the hosting provider&apos;s log retention.
        </p>

        <h2>Who sees what</h2>
        <ul>
          <li>You see your own asks and drafts.</li>
          <li>Admins see account details, approval status and model spend per user.</li>
          <li>
            Managers see only the <a href="/insights">aggregate insights</a> view: counts and topics across all new hires, with groups smaller
            than five suppressed. They never see an individual&apos;s asks.
          </li>
        </ul>

        <h2>Model providers</h2>
        <p>
          The text of your ask, and the synthetic directory records relevant to it, are sent to a language model provider to rank and explain
          candidates and to draft the message. The provider processes it under its API terms. We do not send your email address or password.
        </p>

        <h2>Deleting your data</h2>
        <p>
          Ask an admin to delete your account and everything tied to it is removed: profile, asks, drafts and usage records. Log lines age out of
          the in-memory buffer automatically.
        </p>

        <h2>Contact</h2>
        <p>Questions about this policy go to the team that built the prototype, through the hackathon submission page.</p>
      </DocLayout>
    );
  });
}
