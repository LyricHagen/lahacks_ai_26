import { DocLayout } from "@/components/doc-layout";
import { K_MIN_ASKS } from "@/lib/k-anon";
import { createLogger } from "@/lib/log";
import { withPage } from "@/lib/request-context";

export const metadata = { title: "Privacy policy" };

const log = createLogger("page.privacy");

export default async function PrivacyPage() {
  return withPage("privacy", async () => {
    log.debug("rendering privacy policy");
    return (
      <DocLayout eyebrow="/privacy" title="Privacy policy" description="Last updated 18 October 2026. Plain language: what this app keeps, what it sends where, and how to remove it.">
        <h2>Summary</h2>
        <ul>
          <li>Every colleague, team, calendar, document and message history in Altostratus is synthetic. No real company&apos;s data is in it.</li>
          <li>The only real personal data is your account (email and a password hash) and what you type.</li>
          <li>In demo mode nothing you type leaves our server. In live mode (approved accounts only) your ask goes to a model provider to be read, with what you mark confidential left out.</li>
          <li>Altostratus never sends a message for you and has no access to your Slack, mail or calendar.</li>
          <li>You can delete your account and everything tied to it yourself, on the account page.</li>
        </ul>

        <h2>The company is synthetic</h2>
        <p>
          Ferndale Systems, its 200 people, their skills, calendars, projects, documents and past asks were generated by a script from a fixed
          seed. Names are drawn from lists and matched to nobody. Calendars hold only free and busy blocks. When you play a colleague inside the
          app, you are playing one of these generated people.
        </p>

        <h2>What we collect</h2>
        <h3>Your account</h3>
        <p>
          Your email address, a bcrypt hash of your password (never the password itself), your role, whether an admin approved the account, when
          you signed up and last signed in, and which synthetic colleague you play.
        </p>
        <h3>Your onboarding profile</h3>
        <p>
          The skills you say you already know, what you are working on first, how you prefer to reach people, and whether you are comfortable
          interrupting senior colleagues. They are used only to rank colleagues, write drafts and plan your ramp. Skipped steps store defaults
          taken from your synthetic colleague.
        </p>
        <h3>Your asks</h3>
        <p>
          The text of each problem you describe, what you already tried, how urgent it is, the confirmed reading of it, the shortlist and its
          explanation, the drafted message with your edits, and every change of status with its time (sent, answered). Altostratus does not
          know whether you really sent a message, only what you mark. If you mark an ask answered you can add a one line answer, which is stored
          with the ask.
        </p>
        <h3>Your ramp plan</h3>
        <p>
          Each week&apos;s plan (skill gaps found in your own asks and the documents, colleagues and project it points at) and the items you
          dismissed. The plan refers to your asks by id only, never their text.
        </p>
        <h3>Usage and cost records</h3>
        <p>
          For each model call: the purpose, the model, which tier answered (our fine-tuned model, the frontier model, or a cached demo result),
          token counts, latency and estimated cost, tied to your account so admins can see spend per user. The text sent to the model is not in
          these records.
        </p>
        <h3>Cookies</h3>
        <p>
          Up to three functional cookies, all httpOnly, none used for tracking: the session cookie (up to seven days); the demo mode toggle, only
          if you turn it on; and a random visitor id (90 days), only if you make an ask without signing in, so that browser can see its own asks.
        </p>
        <h3>Rate limit counters</h3>
        <p>
          To stop abuse, the app counts sign in attempts, new asks and model calls per network address and per account. Each counter holds the
          address or account id and a count for one window (at most an hour) and is overwritten after that.
        </p>
        <h3>Logs and error reports</h3>
        <p>
          The server writes detailed technical logs so problems can be debugged. Passwords, keys, the confidential note and anything flagged as
          sensitive are redacted before a line is written. The last 500 lines are kept in memory, and the hosting provider keeps its own logs
          under its retention settings. When error monitoring (Sentry) is switched on, errors and performance timings are sent to it with
          request bodies and cookies removed. Its session replay records the layout and clicks of a page with every piece of text and every
          input masked, so a recording cannot show an ask, a draft or a note.
        </p>

        <h2>What we do not collect</h2>
        <ul>
          <li>The contents of any real email, chat or calendar.</li>
          <li>Anything about you from outside the app.</li>
          <li>Advertising or analytics trackers of any kind.</li>
        </ul>

        <h2 id="model-providers">Model providers</h2>
        <p>Whether anything is sent depends on the mode shown in the header.</p>
        <ul>
          <li>
            <strong>Demo mode</strong> (signed out, pending or rejected accounts, the shared demo account, and anyone with the demo toggle on):
            nothing is sent to any model provider. Results come from answers recorded in advance or from rules in the code. The server checks
            this before every call and refuses otherwise.
          </li>
          <li>
            <strong>Live mode</strong> (approved accounts only): the text of your ask and what you tried go to our fine-tuned model, which runs on a
            GPU we rent from Veri, to read it into services, skills and urgency. If that model is slow or fails, the same text goes to Anthropic
            (Claude). Anthropic also writes the one line reasons on the shortlist (from the synthetic evidence only), the drafted message, and
            your ramp plan sentences.
          </li>
        </ul>
        <p>
          Never sent to any provider: your email address, your password, your confidential note, and the parts of your ask flagged as sensitive
          (they are removed before the drafting step builds its input). Only the reading step sees your full ask text, because it is the step
          that finds the sensitive parts. Providers process requests under their API terms; neither is given your identity.
        </p>

        <h2>Sensitive content exclusion</h2>
        <p>
          When your ask is read, anything that should not reach a colleague is flagged: email addresses, phone numbers, credentials and secrets,
          customer data, and personal or HR sentences. You see these as &quot;leave out&quot; chips on the confirm step and can add or remove
          them. From then on, the flagged text is scrubbed from every later log line of the request and kept out of the draft: any sentence of
          your restatement or of what you tried that contains it is removed before the draft is written, and the draft is checked again
          afterwards.
        </p>
        <p>
          The optional confidential note field is stricter. It is stored only so the draft can leave it out. It is never shown to the person you
          ask, never sent to a model, and never written to logs.
        </p>

        <h2>Aggregate insights</h2>
        <p>
          The <a href="/insights">insights</a> page shows patterns across all new hires (topics, which services lack documents, which documents
          failed, how ask load is spread) so a team can fix the cause. It is built to show groups, never people:
        </p>
        <ul>
          <li>Every number passes a threshold of {K_MIN_ASKS} asks. A topic, week, service or document with fewer is shown as &quot;not enough data&quot;.</li>
          <li>No ask text appears, and nothing says who asked.</li>
          <li>A colleague who was asked is named only when at least {K_MIN_ASKS} asks were sent to them.</li>
          <li>The page exists only while an admin has opted the org in; when it is off, no query behind it runs.</li>
        </ul>

        <h2>Who sees what</h2>
        <ul>
          <li>You see your own asks, drafts and ramp plan. Nobody else&apos;s.</li>
          <li>Admins see account details, approval status and model spend per user, and can open an ask by its address to debug it.</li>
          <li>Managers and everyone else see only the aggregate insights described above.</li>
          <li>
            The <a href="/demo">guided demo</a> uses one shared account. Anything typed in it is visible to anyone else using the demo, so do not
            type anything real there.
          </li>
        </ul>

        <h2>Retention</h2>
        <ul>
          <li>Your account, profile, asks, drafts and ramp plans: until you delete the account.</li>
          <li>Asks made while signed out or in the demo account: until the next Reset demo, which anyone can press and which deletes all of them.</li>
          <li>Usage and cost records: until the account they belong to is deleted.</li>
          <li>Rate limit counters: one window, at most an hour.</li>
          <li>In-memory logs: the last 500 lines, gone on restart. Hosting and error monitoring logs: their providers&apos; retention settings.</li>
          <li>Regenerating the synthetic company clears every ask and plan, but keeps accounts.</li>
        </ul>

        <h2>Deleting your account</h2>
        <p>
          Sign in, open <a href="/account">your account</a>, and use Delete account (type delete to confirm). It removes, in one step, your
          account, profile, asks with their history, drafts, doc checks, ramp plans, dismissals and usage records, then signs you out. It cannot
          be undone. Log lines already written age out as described above. The shared demo account cannot be deleted; Reset demo clears it.
        </p>

        <h2>Contact</h2>
        <p>Questions about this policy go to the team that built the prototype, through the hackathon submission page.</p>
      </DocLayout>
    );
  });
}
